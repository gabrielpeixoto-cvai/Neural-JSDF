import numpy as np
import torch
from torch.utils.data import Dataset, DataLoader, random_split
from pathlib import Path
from typing import Tuple
import os

# --- 1. Custom Dataset Class ---


class SDFDataset(Dataset):
    """
    Custom PyTorch Dataset for loading Signed Distance Function (SDF) data.
    Data format in the file is [x, y, z, d], where d is the SDF value.
    """

    def __init__(self, data_file_path: Path):
        """
        Args:
            data_file_path (Path): Path to the single NumPy (.npy) file containing the SDF data.
        """
        if not data_file_path.exists():
            raise FileNotFoundError(f"Data file not found at: {data_file_path}")

        print(f"Loading data from: {data_file_path.name}...")

        # Load the entire dataset (e.g., N x 4 array)
        self.data = np.load(data_file_path)

        # Convert to PyTorch tensors once
        self.points = torch.tensor(
            self.data[:, :3], dtype=torch.float32
        )  # Features: [x, y, z]
        self.sdfs = torch.tensor(
            self.data[:, 3:], dtype=torch.float32
        )  # Labels: [d] (Note: kept as Nx1 for easier compatibility)

        print(f"Loaded {len(self.data)} samples.")

    def __len__(self):
        """
        Returns the total number of samples in the dataset.
        """
        return len(self.points)

    def __getitem__(self, idx):
        """
        Returns the sample (point coordinates) and the label (SDF value) at index idx.
        """
        # Return features (point) and label (sdf)
        return self.points[idx], self.sdfs[idx]


# --- 2. Data Loader Creation Function ---


def create_dataloaders(
    data_file_path: Path,
    batch_size: int = 64,
    val_split_ratio: float = 0.2,
    seed: int = 42,
) -> Tuple[DataLoader, DataLoader]:
    """
    Creates train and validation DataLoaders for a given SDF data file.

    Args:
        data_file_path (Path): Path to the SDF data file for a single link.
        batch_size (int): Size of the batches for the DataLoader.
        val_split_ratio (float): Fraction of the data to use for validation.
        seed (int): Random seed for reproducible splitting.

    Returns:
        Tuple[DataLoader, DataLoader]: (train_dataloader, val_dataloader)
    """
    # Set seed for reproducibility
    torch.manual_seed(seed)

    # Instantiate the full dataset
    full_dataset = SDFDataset(data_file_path)

    # Determine split sizes
    total_size = len(full_dataset)
    val_size = int(val_split_ratio * total_size)
    train_size = total_size - val_size

    # Split the dataset
    train_dataset, val_dataset = random_split(full_dataset, [train_size, val_size])

    # Create DataLoaders
    train_dataloader = DataLoader(
        train_dataset,
        batch_size=batch_size,
        shuffle=True,  # Shuffle training data
        num_workers=(
            os.cpu_count() // 2 if os.cpu_count() else 0
        ),  # Use half available cores
    )

    val_dataloader = DataLoader(
        val_dataset,
        batch_size=batch_size,
        shuffle=False,  # Do not shuffle validation data
        num_workers=os.cpu_count() // 2 if os.cpu_count() else 0,
    )

    print(f"\nData Loaders created:")
    print(f" - Training samples: {train_size} (Batches: {len(train_dataloader)})")
    print(f" - Validation samples: {val_size} (Batches: {len(val_dataloader)})")

    return train_dataloader, val_dataloader


